import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.connectOverCDP('http://127.0.0.1:9226', { noDefaults: true });
const page = browser.contexts()[0].pages().find(p => p.url().match(/independent-webos-app\/(output\/simulator-build\/)?app\/index\.html/));
assert.ok(page, 'Simulator must have the independent app open');
const report = { date: new Date().toISOString(), environment: 'webOS TV 26 Simulator', steps: [], result: 'RUNNING' };
const savedSkip = await page.evaluate(() => localStorage.getItem('test.skipProfilePrompt'));
let releaseAccount, releaseRecommend;
try {
  await mkdir('output/playwright', { recursive: true });
  await page.evaluate(() => localStorage.removeItem('test.skipProfilePrompt'));
  const accountGate = new Promise(resolve => { releaseAccount = resolve; });
  const recommendGate = new Promise(resolve => { releaseRecommend = resolve; });
  await page.route('**/auth/status', async route => { await accountGate; await route.continue(); });
  await page.route('**/recommend?*', async route => { await recommendGate; await route.continue(); });
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.locator('#startup-screen').waitFor({ state: 'visible' });
  await page.waitForFunction(() => { const img = document.querySelector('#startup-screen img'); return img.complete && img.naturalWidth > 0; });
  assert.equal(await page.locator('#profile-picker').evaluate(n => n.open), false);
  await page.screenshot({ path: 'output/playwright/simulator-startup-logo.png' });
  report.steps.push('white vector wordmark precedes account picker');
  releaseAccount();
  await page.locator('#startup-screen').waitFor({ state: 'hidden', timeout: 60000 });
  await page.locator('#profile-picker').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#profile-picker-title').innerText(), '谁在观看？');
  assert.equal(await page.locator('#profile-picker').evaluate(n => n.classList.contains('panel')), false);
  assert.equal(await page.evaluate(() => document.activeElement.classList.contains('profile-choice')), true);
  report.savedAccounts = await page.locator('#profile-choices [data-tint]').count();
  assert.ok(report.savedAccounts > 0, 'Real-session test needs a saved account to enter home');
  await page.screenshot({ path: 'output/playwright/simulator-startup-accounts.png' });
  report.steps.push('full-screen account picker opens with account focus');
  const index = () => page.evaluate(() => Array.from(document.querySelector('#profile-choices').children).indexOf(document.activeElement));
  const initial = await index();
  const count = await page.locator('#profile-choices button').count();
  const step = initial < count - 1 ? 1 : -1;
  await page.keyboard.press(step === 1 ? 'ArrowRight' : 'ArrowLeft');
  assert.equal(await index(), initial + step);
  await page.keyboard.press(step === 1 ? 'ArrowLeft' : 'ArrowRight');
  assert.equal(await index(), initial);
  report.steps.push('Left/Right moves account focus and returns');
  await page.keyboard.press('Enter');
  await page.locator('#profile-picker').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.activeElement.id === 'hero-play');
  assert.equal(await page.evaluate(() => recommendBusy), true);
  await page.keyboard.press('ArrowLeft');
  assert.equal(await page.evaluate(() => document.activeElement.dataset.page), 'browse');
  await page.keyboard.press('ArrowRight');
  report.steps.push('home navigation works while the recommendation response is still pending');
  releaseRecommend();
  await page.waitForFunction(() => document.querySelector('#recommend-grid .video-card') && document.activeElement.id === 'hero-play', null, { timeout: 60000 });
  await page.screenshot({ path: 'output/playwright/simulator-startup-home.png' });
  report.steps.push('Enter selects current account and opens populated home with hero focus');
  report.result = 'PASS';
} catch (error) {
  report.result = 'FAIL'; report.error = error.message; throw error;
} finally {
  releaseAccount?.();
  releaseRecommend?.();
  await page.unroute('**/auth/status');
  await page.unroute('**/recommend?*');
  await page.evaluate(value => { if (value === null) localStorage.removeItem('test.skipProfilePrompt'); else localStorage.setItem('test.skipProfilePrompt', value); }, savedSkip);
  await writeFile('output/playwright/simulator-startup.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
  await browser.close();
}
